let cachedCatalog = null;

export function getEmojiCatalog() {
  if (cachedCatalog) return cachedCatalog;
  const groups = {};
  const byEmoji = new Map();
  const all = [];

  for (const cat of EMOJI_CATEGORIES) {
    if (cat.id === 'recent') continue;
    const lines = RAW_EMOJI_PACK[cat.id] || [];
    const parsed = lines.map((row) => {
      const [emoji, name, rawShortcode = '', extraKw = ''] = row.split('\t');
      const shortcode = rawShortcode.trim().replace(/\s+/g, '_');
      const searchBlob = `${name.toLowerCase()} ${shortcode.toLowerCase().replace(/_/g, ' ')} ${extraKw}`;
      const item = { emoji, name, shortcode, category: cat.id, searchBlob };
      byEmoji.set(emoji, item);
      all.push(item);
      return item;
    });
    groups[cat.id] = parsed;
  }

  cachedCatalog = { groups, byEmoji, all };
  return cachedCatalog;
}

export function readRecentEmojis() {
  if (typeof window === 'undefined') return [];
  try {
    const raw = window.localStorage.getItem(RECENT_EMOJIS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((x) => typeof x === 'string' && x.length > 0).slice(0, MAX_RECENT_EMOJIS);
  } catch {
    return [];
  }
}

export function recordRecentEmoji(emoji) {
  if (typeof window === 'undefined' || !emoji) return [];
  const prev = readRecentEmojis();
  const next = [emoji, ...prev.filter((x) => x !== emoji)].slice(0, MAX_RECENT_EMOJIS);
  try {
    window.localStorage.setItem(RECENT_EMOJIS_STORAGE_KEY, JSON.stringify(next));
  } catch {
    // ignore storage quota errors
  }
  return next;
}

export function searchEmojiCatalog(query = '') {
  const clean = String(query || '').toLowerCase().replace(/^:+|:+$/g, '').trim();
  const { all } = getEmojiCatalog();
  if (!clean) return all;
  const terms = clean.split(/\s+/).filter(Boolean);
  const exact = [];
  const starts = [];
  const wordStarts = [];
  const contains = [];

  for (const item of all) {
    if (item.emoji === clean) {
      exact.push(item);
      continue;
    }
    let matchesAll = true;
    for (const t of terms) {
      if (!item.searchBlob.includes(t) && !item.shortcode.includes(t)) {
        matchesAll = false;
        break;
      }
    }
    if (!matchesAll) continue;
    const nameLower = item.name.toLowerCase();
    if (item.shortcode === clean || nameLower === clean) {
      exact.push(item);
    } else if (item.shortcode.startsWith(terms[0]) || nameLower.startsWith(terms[0])) {
      starts.push(item);
    } else if (
      nameLower.split(/[\s_-]+/).some((w) => w.startsWith(terms[0])) ||
      item.searchBlob.split(/\s+/).some((w) => w.startsWith(terms[0]))
    ) {
      wordStarts.push(item);
    } else {
      contains.push(item);
    }
  }

  return [...exact, ...starts, ...wordStarts, ...contains];
}
